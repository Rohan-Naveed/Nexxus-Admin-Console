import { useMemo, useState } from "react";
import { History } from "lucide-react";

function formatDateTime(value) {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}

export default function SlipActivityHistory({ events, dispatchers }) {
  const [dispatcherFilter, setDispatcherFilter] = useState("all");

  const sorted = useMemo(
    () =>
      [...events]
        .filter(
          (event) =>
            dispatcherFilter === "all" ||
            String(event.dispatcherId) === dispatcherFilter,
        )
        .sort((a, b) => new Date(b.eventAt) - new Date(a.eventAt)),
    [events, dispatcherFilter],
  );

  return (
    <div className="panel">
      <div className="section-head">
        <div>
          <div className="panel-title">Generation &amp; email history</div>
          <div className="panel-sub">
            Every recorded slip generation and successful email delivery, newest
            first.
          </div>
        </div>
        <select
          className="form-select"
          style={{ maxWidth: 220 }}
          value={dispatcherFilter}
          onChange={(event) => setDispatcherFilter(event.target.value)}
          aria-label="Filter slip activity by employee"
        >
          <option value="all">All employees</option>
          {dispatchers.map((dispatcher) => (
            <option key={dispatcher.id} value={dispatcher.id}>
              {dispatcher.alias || dispatcher.name}
            </option>
          ))}
        </select>
      </div>

      {sorted.length === 0 ? (
        <div className="empty-row">
          <History
            size={14}
            style={{ marginRight: 6, verticalAlign: "-2px" }}
          />
          No slip activity recorded yet.
        </div>
      ) : (
        <div className="table-shell">
          <table>
            <thead>
              <tr>
                {[
                  "Employee",
                  "Period",
                  "Activity",
                  "Date and time",
                  "Details",
                ].map((header) => (
                  <th key={header} className="table-head">
                    {header}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {sorted.map((event) => (
                <tr key={event.id}>
                  <td className="table-cell table-cell-strong">
                    {event.dispatchAlias || event.dispatcherName}
                    {event.dispatchAlias &&
                    event.dispatchAlias !== event.dispatcherName
                      ? ` (${event.dispatcherName})`
                      : ""}
                  </td>
                  <td className="table-cell">
                    {new Date(
                      event.periodYear,
                      event.periodMonth - 1,
                    ).toLocaleDateString("en-US", {
                      month: "long",
                      year: "numeric",
                    })}
                  </td>
                  <td className="table-cell">
                    {event.eventType === "email_sent" ? (
                      <span className="pill pill-route">Email sent</span>
                    ) : (
                      <span className="pill">Generated</span>
                    )}
                  </td>
                  <td className="table-cell">
                    {formatDateTime(event.eventAt)}
                  </td>
                  <td className="table-cell">
                    {event.eventType === "email_sent"
                      ? event.email || "Email recipient unavailable"
                      : event.actor || "Generated by an unknown user"}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
